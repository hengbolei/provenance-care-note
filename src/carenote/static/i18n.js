const MESSAGES = { en, "zh-Hans": zhHans, "zh-Hant": zhHant };

let currentLanguage = detectLanguage();
const listeners = new Set();

function detectLanguage() {
  try {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (stored && LANGUAGES[stored]) return stored;
  } catch {
    // Storage can be unavailable; fall back to the browser language.
  }
  const preferred = (navigator.languages || [navigator.language || "en"]).map((value) =>
    String(value).toLowerCase(),
  );
  for (const value of preferred) {
    if (/^zh-(hant|tw|hk|mo)/.test(value)) return "zh-Hant";
    if (value.startsWith("zh")) return "zh-Hans";
    if (value.startsWith("en")) return "en";
  }
  return "en";
}

export function getLanguage() {
  return currentLanguage;
}

export function getLocale() {
  return LANGUAGES[currentLanguage].locale;
}

export function t(key, params = {}) {
  let message = MESSAGES[currentLanguage][key] ?? en[key] ?? key;
  if (typeof message === "object") {
    message = params.count === 1 ? message.one : message.other;
  }
  return message.replace(/\{(\w+)\}/g, (match, name) =>
    params[name] === undefined ? match : String(params[name]),
  );
}

export function applyTranslations(root = document) {
  document.documentElement.lang = LANGUAGES[currentLanguage].htmlLang;
  root.querySelectorAll("[data-i18n]").forEach((node) => {
    node.textContent = t(node.dataset.i18n);
  });
  for (const attribute of ["placeholder", "aria-label", "title"]) {
    root.querySelectorAll(`[data-i18n-${attribute}]`).forEach((node) => {
      node.setAttribute(attribute, t(node.getAttribute(`data-i18n-${attribute}`)));
    });
  }
}

export function setLanguage(language) {
  if (!LANGUAGES[language] || language === currentLanguage) return;
  currentLanguage = language;
  try {
    localStorage.setItem(STORAGE_KEY, language);
  } catch {
    // The choice still applies for this page view.
  }
  applyTranslations();
  listeners.forEach((listener) => listener(language));
}

export function onLanguageChange(listener) {
  listeners.add(listener);
}

