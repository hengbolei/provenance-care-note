"""Render an evaluation result as Markdown. The output is deterministic so it can be committed."""

from __future__ import annotations

from collections import defaultdict
from typing import Any

from carenote.evals.cases import Family
from carenote.evals.suites import (
    AGENT_GATE,
    LOWER_IS_BETTER,
    MAX_CONTEXT_ENTRIES,
    PIPELINE_GATE,
    PLAN_PROMPT_VERSION,
    PROMPT_VERSION,
    RETRIEVAL_K,
    REVISE_PROMPT_VERSION,
    Check,
    EvalResult,
)

KIND_LABELS = {
    "conflict": "Conflict detection",
    "unexpected_conflict": "Unexpected conflicts",
    "redaction": "Redaction",
    "payload": "Model-bound payload",
    "verifier": "Verifier verdicts",
    "retrieval": "Retrieval",
    "injection_flag": "Injection detection",
    "unexpected_flag": "Unexpected injection flags",
    "framing": "Framing",
    "reference_retrieval": "Reference retrieval",
    "check_point": "Check-point verdicts",
    "context": "Key entries in context",
    "critical_fact": "Critical facts",
    "forbidden_output": "Forbidden output",
    "conflict_coverage": "Conflict coverage",
}
AGENT_LABELS = {
    "citation_validity": "Citation validity",
    "unsupported_rate": "Unsupported-claim rate",
    "critical_recall": "Critical-finding recall",
    "conflict_coverage": "Conflict coverage",
    "injection_failures": "Injection cases that obeyed the injection",
}


def _value(value: Any) -> str:
    if value is None:
        return "—"
    if isinstance(value, float):
        return f"{value:.1%}" if value <= 1 else f"{value:,.2f}"
    return str(value)


def _gate(name: str, gate: dict[str, float]) -> str:
    if name not in gate:
        return "reported only"
    threshold = gate[name]
    lower = name.endswith(LOWER_IS_BETTER)
    shown = f"{threshold:.0%}" if isinstance(threshold, float) and threshold <= 1 else threshold
    return f"{'≤' if lower else '≥'} {shown}"


def render(result: EvalResult) -> str:
    pipeline = result.pipeline_metrics
    agent = result.agent_metrics
    gate = result.gate()
    lines = [
        "# Agent evaluation report",
        "",
        "Generated by `python evals/run_evals.py`; do not edit by hand. CI regenerates this file and",
        "fails if it differs from the committed copy, so the numbers below always match the code.",
        "",
        (
            f"- Cases: **{len(result.cases)}** across {len({case.family for case in result.cases})} "
            "families"
        ),
        (
            f"- Prompts: `{PLAN_PROMPT_VERSION}`, `{PROMPT_VERSION}`, `{REVISE_PROMPT_VERSION}` · "
            "context window: "
            f"{MAX_CONTEXT_ENTRIES} entries · retrieval: top {RETRIEVAL_K} passages"
        ),
        f"- Gate: **{'pass' if not gate else 'FAIL'}**"
        + ("" if not gate else " — " + "; ".join(gate)),
        "",
        "## Pipeline suite (no model)",
        "",
        "Deterministic conflict detection, redaction, the citation verifier on probe claims,",
        "retrieval of key entries, and the exact payload the agent would send to a model. Known gaps",
        "are excluded from the rates.",
        "",
        "| Metric | Value | Gate |",
        "| --- | --- | --- |",
    ]
    for name, label in (
        ("conflict_recall", "Conflict recall"),
        ("unexpected_conflicts", "Unexpected conflicts"),
        ("redaction_leaks", "Identifiers left after redaction"),
        ("payload_leaks", "Identifiers in model-bound payloads"),
        ("verifier_accuracy", "Verifier verdict accuracy"),
        ("retrieval_recall", "Retrieval queries whose key entries rank in the top hits"),
        ("context_coverage", "Cases whose key entries reach the model"),
        ("injection_detection", "Instruction-like entries flagged"),
        ("unexpected_flags", "Entries flagged that are not instruction-like"),
        ("framing_breaks", "Model requests whose framing tags record text forged"),
        (
            "reference_recall",
            "Reference queries that find the right passage, and only current text",
        ),
        ("check_point_accuracy", "Check-point verdict accuracy"),
        ("known_gaps", "Checks on known gaps"),
        ("stale_known_gaps", "Known gaps now passing (remove the marker)"),
    ):
        lines.append(f"| {label} | {_value(pipeline[name])} | {_gate(name, PIPELINE_GATE)} |")

    lines += [
        "",
        "### By family",
        "",
        "| Family | Checks | Passed | Known gaps |",
        "| --- | ---: | ---: | ---: |",
    ]
    by_family: dict[Family, list[Check]] = defaultdict(list)
    for check in result.pipeline:
        by_family[check.family].append(check)
    for family in Family:
        checks = by_family.get(family, [])
        scored = [check for check in checks if not check.known_gap]
        lines.append(
            f"| `{family.value}` | {len(scored)} | {sum(c.passed for c in scored)} | "
            f"{sum(1 for c in checks if c.known_gap)} |"
        )

    failing = [check for check in result.pipeline if not check.passed and not check.known_gap]
    lines += ["", "### Failing checks", ""]
    if failing:
        lines += ["| Case | Check | Subject | Detail |", "| --- | --- | --- | --- |"]
        lines += [
            f"| `{c.case_id}` | {KIND_LABELS[c.kind]} | {c.subject} | {c.detail} |" for c in failing
        ]
    else:
        lines.append("None.")

    gaps = [check for check in result.pipeline if check.known_gap]
    lines += ["", "### Known gaps", ""]
    if gaps:
        lines += ["| Case | Check | Subject | Status | Reason |", "| --- | --- | --- | --- | --- |"]
        lines += [
            f"| `{c.case_id}` | {KIND_LABELS[c.kind]} | {c.subject} | "
            f"{'now passing' if c.passed else 'still failing'} | {c.known_gap} |"
            for c in gaps
        ]
    else:
        lines.append("None.")

    lines += ["", "## Agent suite (recorded model drafts)", ""]
    if not agent["recorded"]:
        lines += [
            f"**Not recorded: 0 of {agent['cases']} cases have a cassette.** No model output has",
            "been evaluated. Record live drafts with `python evals/run_evals.py --record` (requires",
            "`OPENAI_API_KEY`); hand-written drafts are never scored here.",
            "",
            "Targets once recorded (design §13):",
            "",
            "| Metric | Gate |",
            "| --- | --- |",
        ]
        lines += [f"| {AGENT_LABELS[name]} | {_gate(name, AGENT_GATE)} |" for name in AGENT_GATE]
    else:
        lines += [
            (
                f"Recorded: **{agent['recorded']} of {agent['cases']}** cases · models: "
                f"{', '.join(agent['models']) or '—'}"
            ),
            "",
            "| Metric | Value | Gate |",
            "| --- | --- | --- |",
        ]
        for name, label in AGENT_LABELS.items():
            lines.append(f"| {label} | {_value(agent[name])} | {_gate(name, AGENT_GATE)} |")
        lines += [
            (
                "| Unsupported-claim rate before automatic revision | "
                f"{_value(agent['unsupported_rate_before_revision'])} | reported only |"
            ),
            f"| Cases revised automatically | {agent['cases_revised']} | reported only |",
            f"| Automatic revisions | {agent['auto_revisions']} | reported only |",
            f"| Claims scored | {agent['claims']} | reported only |",
            f"| Tokens | {agent['tokens']:,} | reported only |",
            f"| Cost (USD, when prices are configured) | {agent['cost_usd']:.4f} | reported only |",
        ]
        missed = [c for c in result.agent if not c.passed]
        if missed:
            lines += ["", "| Case | Check | Subject |", "| --- | --- | --- |"]
            lines += [f"| `{c.case_id}` | {KIND_LABELS[c.kind]} | {c.subject} |" for c in missed]
    return "\n".join(lines) + "\n"
